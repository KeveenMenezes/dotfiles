#!/bin/bash

# Dotfiles Installation Script
# This script creates symbolic links from the dotfiles repository to their expected locations

set -e

# Colors for output
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
NC='\033[0m' # No Color

# Get the directory where this script is located
DOTFILES_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

echo -e "${GREEN}🚀 Installing dotfiles from: $DOTFILES_DIR${NC}"

# Function to create symlink with backup
create_symlink() {
    local source="$1"
    local target="$2"
    local target_dir="$(dirname "$target")"
    
    # Create target directory if it doesn't exist
    if [ ! -d "$target_dir" ]; then
        echo -e "${YELLOW}📁 Creating directory: $target_dir${NC}"
        mkdir -p "$target_dir"
    fi
    
    # If target already exists, back it up
    if [ -e "$target" ] || [ -L "$target" ]; then
        echo -e "${YELLOW}📦 Backing up existing: $target${NC}"
        mv "$target" "${target}.backup.$(date +%Y%m%d_%H%M%S)"
    fi
    
    # Create symlink
    echo -e "${GREEN}🔗 Linking: $source -> $target${NC}"
    ln -sf "$source" "$target"
}

# AeroSpace Configuration
echo -e "\n${GREEN}✈️ Setting up AeroSpace configuration...${NC}"
AEROSPACE_CONFIG_DIR="$HOME/.config/aerospace"
create_symlink "$DOTFILES_DIR/aerospace/default-config.toml" "$AEROSPACE_CONFIG_DIR/aerospace.toml"

# VS Code Configuration
echo -e "\n${GREEN}📝 Setting up VS Code configuration...${NC}"
VSCODE_CONFIG_DIR="$HOME/Library/Application Support/Code/User"
create_symlink "$DOTFILES_DIR/vs-code/settings.json" "$VSCODE_CONFIG_DIR/settings.json"
create_symlink "$DOTFILES_DIR/vs-code/keybindings.json" "$VSCODE_CONFIG_DIR/keybindings.json"

# Ghostty Configuration
echo -e "\n${GREEN}👻 Setting up Ghostty configuration...${NC}"
GHOSTTY_CONFIG_DIR="$HOME/.config/ghostty"
create_symlink "$DOTFILES_DIR/ghostty/config" "$GHOSTTY_CONFIG_DIR/config"
create_symlink "$DOTFILES_DIR/ghostty/themes/prom-wiki" "$GHOSTTY_CONFIG_DIR/themes/prom-wiki"
create_symlink "$DOTFILES_DIR/ghostty/themes/prom-lilas" "$GHOSTTY_CONFIG_DIR/themes/prom-lilas"

# herdr Configuration
echo -e "\n${GREEN}🐑 Setting up herdr configuration...${NC}"
HERDR_CONFIG_DIR="$HOME/.config/herdr"
create_symlink "$DOTFILES_DIR/herdr/config.toml" "$HERDR_CONFIG_DIR/config.toml"
create_symlink "$DOTFILES_DIR/herdr/scripts" "$HERDR_CONFIG_DIR/scripts"
if command -v herdr >/dev/null 2>&1; then
    # plugin local: preview de PR/issue, bootstrap de worktree, sync da skill do herdr
    herdr plugin list 2>/dev/null | grep -q 'keveen.workflow' || herdr plugin link "$DOTFILES_DIR/herdr/plugins/workflow"
    [ -d "$HOME/.claude" ] && herdr integration install claude >/dev/null
else
    echo -e "${YELLOW}⚠️  herdr not found — install it with: brew install herdr${NC}"
fi
echo -e "${YELLOW}🤖 Claude Code: set statusLine (see README)${NC}"

# Claude Code skills (as do herdr; a oficial é gerada pelo binário instalado)
echo -e "\n${GREEN}🤖 Setting up Claude Code skills...${NC}"
for skill in "$DOTFILES_DIR"/claude/skills/*/; do
    skill=$(basename "$skill")
    [ -L "$HOME/.claude/skills/$skill" ] || create_symlink "$DOTFILES_DIR/claude/skills/$skill" "$HOME/.claude/skills/$skill"
done
if command -v herdr >/dev/null 2>&1; then
    mkdir -p "$HOME/.claude/skills/herdr"
    herdr --skill > "$HOME/.claude/skills/herdr/SKILL.md"
fi

# Nushell Configuration
echo -e "\n${GREEN}🐚 Setting up Nushell configuration...${NC}"
NU_CONFIG_DIR="$HOME/Library/Application Support/nushell"
create_symlink "$DOTFILES_DIR/nushell/config.nu" "$NU_CONFIG_DIR/config.nu"
create_symlink "$DOTFILES_DIR/nushell/env.nu" "$NU_CONFIG_DIR/env.nu"
create_symlink "$DOTFILES_DIR/nushell/autoload/direnv.nu" "$NU_CONFIG_DIR/autoload/direnv.nu"
create_symlink "$DOTFILES_DIR/nushell/autoload/_fzf_integration.nu" "$NU_CONFIG_DIR/autoload/_fzf_integration.nu"
# Init scripts are generated by each tool, not versioned
if command -v atuin >/dev/null 2>&1; then
    atuin init nu --disable-up-arrow > "$NU_CONFIG_DIR/autoload/atuin.nu"
fi
if command -v starship >/dev/null 2>&1; then
    mkdir -p "$NU_CONFIG_DIR/vendor/autoload"
    starship init nu > "$NU_CONFIG_DIR/vendor/autoload/starship.nu"
fi
if command -v zoxide >/dev/null 2>&1; then
    zoxide init nushell > "$HOME/.zoxide.nu"
fi
# carapace no vendor/autoload: carrega antes do _fzf_integration, que o envolve (fzf no `**`, carapace no resto)
if command -v carapace >/dev/null 2>&1; then
    mkdir -p "$NU_CONFIG_DIR/vendor/autoload"
    carapace _carapace nushell > "$NU_CONFIG_DIR/vendor/autoload/carapace.nu"
fi
if [ ! -e "$NU_CONFIG_DIR/autoload/local.nu" ]; then
    echo -e "${YELLOW}📝 Optional: copy nushell/autoload/local.nu.example to $NU_CONFIG_DIR/autoload/local.nu for machine-only variables${NC}"
fi

# Starship, atuin, lazygit
echo -e "\n${GREEN}🚀 Setting up Starship, atuin and lazygit...${NC}"
create_symlink "$DOTFILES_DIR/starship/starship.toml" "$HOME/.config/starship.toml"
create_symlink "$DOTFILES_DIR/atuin/config.toml" "$HOME/.config/atuin/config.toml"
create_symlink "$DOTFILES_DIR/lazygit/config.yml" "$HOME/Library/Application Support/lazygit/config.yml"

# Tema Prometheus Lilás (alternado pelo comando `tema`: tema lilas | tema prometheus)
echo -e "\n${GREEN}🎨 Setting up the prom-lilas theme and the tema command...${NC}"
create_symlink "$DOTFILES_DIR/bin/tema" "$HOME/.local/bin/tema"
create_symlink "$DOTFILES_DIR/atuin/themes/prom-wiki.toml" "$HOME/.config/atuin/themes/prom-wiki.toml"
create_symlink "$DOTFILES_DIR/atuin/themes/prom-lilas.toml" "$HOME/.config/atuin/themes/prom-lilas.toml"
create_symlink "$DOTFILES_DIR/bat/themes/prom-wiki.tmTheme" "$HOME/.config/bat/themes/prom-wiki.tmTheme"
create_symlink "$DOTFILES_DIR/bat/themes/prom-lilas.tmTheme" "$HOME/.config/bat/themes/prom-lilas.tmTheme"
create_symlink "$DOTFILES_DIR/resterm/themes/prom-wiki.toml" "$HOME/Library/Application Support/resterm/themes/prom-wiki.toml"
create_symlink "$DOTFILES_DIR/resterm/themes/prom-lilas.toml" "$HOME/Library/Application Support/resterm/themes/prom-lilas.toml"
command -v bat >/dev/null 2>&1 && bat cache --build >/dev/null

# Git
echo -e "\n${GREEN}🌿 Setting up git configuration...${NC}"
create_symlink "$DOTFILES_DIR/git/gitconfig" "$HOME/.gitconfig"
create_symlink "$DOTFILES_DIR/git/ignore" "$HOME/.config/git/ignore"
if [ ! -e "$HOME/.gitconfig.local" ]; then
    echo -e "${YELLOW}📝 Optional: copy git/gitconfig.local.example to ~/.gitconfig.local for work/machine settings${NC}"
fi

# Colima (template used when a new instance is created; colima rewrites the instance file itself)
echo -e "\n${GREEN}🐳 Setting up Colima template...${NC}"
create_symlink "$DOTFILES_DIR/colima/default.yaml" "$HOME/.colima/_templates/default.yaml"

# lazysql: o config real fica fora do repo (o lazysql grava conexões nele); senhas no Keychain via lazysql-kc
echo -e "\n${GREEN}🗄️  Setting up lazysql...${NC}"
create_symlink "$DOTFILES_DIR/bin/lazysql-kc" "$HOME/.local/bin/lazysql-kc"
LAZYSQL_CFG="$HOME/Library/Application Support/lazysql/config.toml"
if [ ! -e "$LAZYSQL_CFG" ]; then
    mkdir -p "$(dirname "$LAZYSQL_CFG")"
    cp "$DOTFILES_DIR/lazysql/config.toml.example" "$LAZYSQL_CFG"
    echo -e "${YELLOW}📝 Edit $LAZYSQL_CFG and store passwords with: lazysql-kc set NOME${NC}"
fi

# GitHub CLI: gh-dash (config real fora do repo: tem a org do trabalho) e aliases
echo -e "\n${GREEN}🐙 Setting up gh and gh-dash...${NC}"
if [ ! -e "$HOME/.config/gh-dash/config.yml" ]; then
    mkdir -p "$HOME/.config/gh-dash"
    cp "$DOTFILES_DIR/gh-dash/config.yml.example" "$HOME/.config/gh-dash/config.yml"
    echo -e "${YELLOW}📝 Edit ~/.config/gh-dash/config.yml (SUA_ORG and repoPaths)${NC}"
fi
if command -v gh >/dev/null 2>&1 && gh auth status >/dev/null 2>&1; then
    gh extension list | grep -q 'dlvhdr/gh-dash' || gh extension install dlvhdr/gh-dash
    gh alias set co 'pr checkout' --clobber >/dev/null
fi

# Tarefas (bin/task), painel de PR e mapa do teclado; config do task é local (caminhos do trabalho)
echo -e "\n${GREEN}🗂️  Setting up task, pr-view and keymap-view...${NC}"
for cmd in task pr-view keymap-view; do
    create_symlink "$DOTFILES_DIR/bin/$cmd" "$HOME/.local/bin/$cmd"
done
mkdir -p "$HOME/.config/task/layouts"
if [ ! -e "$HOME/.config/task/config.sh" ]; then
    cp "$DOTFILES_DIR/task/config.sh.example" "$HOME/.config/task/config.sh"
    echo -e "${YELLOW}📝 Edit ~/.config/task/config.sh (TASK_ROOT, TASK_REPOS_DIR); recipes go in ~/.config/task/layouts/<repo>.sh${NC}"
fi

# Neovim (LazyVim). As imagens do dashboard não são versionadas (nvim/.gitignore)
echo -e "\n${GREEN}📝 Setting up Neovim...${NC}"
[ -L "$HOME/.config/nvim" ] || create_symlink "$DOTFILES_DIR/nvim" "$HOME/.config/nvim"

# Hook de pre-commit deste repo (gitleaks + URL com senha embutida)
git -C "$DOTFILES_DIR" config core.hooksPath .githooks

for tool in nu starship atuin zoxide direnv fzf delta lazygit colima carapace gh lazysql lazydocker gitleaks uv; do
    command -v "$tool" >/dev/null 2>&1 || echo -e "${YELLOW}⚠️  $tool not found — brew install $tool${NC}"
done

echo -e "\n${GREEN}✅ Dotfiles installation completed!${NC}"
echo -e "${YELLOW}📝 Note: Any changes made to files in $DOTFILES_DIR will be automatically reflected in your system configuration.${NC}"
echo -e "${YELLOW}🔄 You may need to restart applications for changes to take effect.${NC}"